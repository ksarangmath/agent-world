export const places: Place[] = Object.entries(rows).flatMap(([region, list]) =>
  list.map(([id, name, neighborhood, activity, [lat, lon], capacity, tags, description]) => {
    const [x, y] = warp(lon, lat)
    const center = { x: Math.round(x), y: Math.round(y) }
    return {
      id,
      name,
      region: region as Region,
      neighborhood,
      description,
      tags,
      activity,
      center,
      capacity,
    }
  }),
)

export const placesById: ReadonlyMap<string, Place> = new Map(
  places.map((place) => [place.id, place]),
)
