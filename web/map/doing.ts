function hash(text: string) {
  let value = 2166136261
  for (let i = 0; i < text.length; i++) value = Math.imul(value ^ text.charCodeAt(i), 16777619)
  return value >>> 0
}

export function doingNow(person: WorldPerson, people: WorldPerson[], now = Date.now()) {
  const place = placesById.get(person.placeId)
  if (person.trip) return `on the way to ${place?.name ?? 'somewhere'}`
  if (person.asleep) return 'fast asleep'
  if (person.conversationId) {
    const partner = people.find(
      (other) => other.id !== person.id && other.conversationId === person.conversationId,
    )
    if (partner) return `deep in it with ${partner.name}`
  }
  const lines = doing[person.placeId]
  if (!lines) return 'taking it all in'
  const start = hash(person.id)
  const turn = Math.floor((now + (start % changeEveryMs)) / changeEveryMs)
  return lines[(start + turn) % lines.length]!
}
