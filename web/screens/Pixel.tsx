export type PixelName = keyof typeof art

export function Pixel({ name }: { name: PixelName }) {
  const rows = art[name]
  const top = (8 - rows.length) / 2
  const path = rows
    .flatMap((row, y) => [...row].map((dot, x) => (dot === '#' ? `M${x} ${y + top}h1v1h-1z` : '')))
    .join('')
  return (
    <svg className="pixel" viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden="true">
      <path d={path} fill="currentColor" />
    </svg>
  )
}
